/*
Generate src/iconAssets.js which exports a mapping of iconName -> require('../assets/icons/<name>.png')
Usage:
  cd mobile
  node scripts/generate-icon-assets.js

This script expects PNG files to exist in assets/icons (created by download-icons.ps1 and ImageMagick or manually).
*/

const fs = require('fs');
const path = require('path');

const assetsDir = path.join(__dirname, '..', 'assets', 'icons');
const outFile = path.join(__dirname, '..', 'src', 'iconAssets.js');

if (!fs.existsSync(assetsDir)) {
  console.error('assets/icons directory not found:', assetsDir);
  process.exit(1);
}

const files = fs.readdirSync(assetsDir).filter(f => f.toLowerCase().endsWith('.png'));
const entries = files.map(f => {
  const name = path.basename(f, '.png');
  // require path relative to src/iconAssets.js -> ../assets/icons/<file>
  const reqPath = `../assets/icons/${f}`;
  return `  '${name}': require('${reqPath}')`;
});

const content = `// This file is auto-generated by scripts/generate-icon-assets.js
// Do not edit by hand. Regenerate after changing assets/icons/

export default {
${entries.join(',\n')}
};
`;

fs.writeFileSync(outFile, content, 'utf8');
console.log('Wrote', outFile, 'with', entries.length, 'entries');
