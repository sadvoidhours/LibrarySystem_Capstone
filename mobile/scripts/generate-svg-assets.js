/*
Generate src/iconSvgAssets.js mapping for SVG files in assets/icons-svg
Usage:
  cd mobile
  node scripts/generate-svg-assets.js
*/

const fs = require('fs');
const path = require('path');

const assetsDir = path.join(__dirname, '..', 'assets', 'icons-svg');
const outFile = path.join(__dirname, '..', 'src', 'iconSvgAssets.js');

if (!fs.existsSync(assetsDir)) {
  console.error('assets/icons-svg directory not found:', assetsDir);
  process.exit(1);
}

const files = fs.readdirSync(assetsDir).filter(f => f.toLowerCase().endsWith('.svg'));
const entries = files.map(f => {
  const name = path.basename(f, '.svg');
  // require path relative to src/iconSvgAssets.js -> ../assets/icons-svg/<file>
  const reqPath = `../assets/icons-svg/${f}`;
  return `  '${name}': require('${reqPath}')`;
});

const content = `// This file is auto-generated by scripts/generate-svg-assets.js
// Do not edit by hand. Regenerate after changing assets/icons-svg/

export default {
${entries.join(',\n')}
};
`;

fs.writeFileSync(outFile, content, 'utf8');
console.log('Wrote', outFile, 'with', entries.length, 'entries');
